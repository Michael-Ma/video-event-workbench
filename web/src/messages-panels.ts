/** Translate a whole sentence before interpolation, preserving English word order. */
export function panelMessage(message: string, values: Record<string, string | number>): string {
  return t(message).replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder);
}
